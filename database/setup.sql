create table IMS_ACCOUNT (
 id number generated by default as identity primary key,
 role varchar2(12) not null check(role in ('ADMIN','EMPLOYEE','CUSTOMER')),
 parent_id references IMS_ACCOUNT(id) on delete set null,
 name varchar2(120) not null, username varchar2(80) not null,
 password varchar2(200) not null, email varchar2(160), phone varchar2(40), address varchar2(300),
 active number(1) default 1 not null,
 discount number(5,2) default 0 not null check(discount between 0 and 100),
 discount_start date, discount_end date, discount_active number(1) default 0 not null,
 unique(role,username)
);
create table IMS_SHOP (id number generated always as identity primary key, name varchar2(120) not null, address varchar2(300), active number(1) default 1 not null constraint IMS_SHOP_ACTIVE_CK check(active in (0,1)));
alter table IMS_SHOP add (warehouse number(1) default 0 not null
    constraint IMS_SHOP_WAREHOUSE_CK check (warehouse in (0,1)));
create unique index IMS_SINGLE_WAREHOUSE on IMS_SHOP (case when warehouse=1 then 1 end);
create unique index IMS_SHOP_UNIQUE_NAME on IMS_SHOP (lower(trim(name)));
create table IMS_SUPPLIER (id number generated always as identity primary key, name varchar2(120) not null, phone varchar2(40), email varchar2(160), address varchar2(300));
create table IMS_CATEGORY (id number generated always as identity primary key, name varchar2(120) not null, parent_id references IMS_CATEGORY(id));
create table IMS_PRODUCT (
 id number generated always as identity primary key, name varchar2(120) not null,
 category_id references IMS_CATEGORY(id) not null, supplier_id references IMS_SUPPLIER(id) not null,
 cost number(12,2) not null check(cost>=0), price number(12,2) not null check(price>=0),
 alarm number(9) not null check(alarm>=0), active number(1) default 1 not null);
create table IMS_STOCK (
 shop_id references IMS_SHOP(id), product_id references IMS_PRODUCT(id),
 quantity number(9) not null check(quantity>=0), location varchar2(120),
  updated_at date default sysdate not null,
 max_quantity number(9),
 constraint IMS_STOCK_MAX_QTY_CK check (max_quantity >= 1 and quantity <= max_quantity),
 primary key(shop_id,product_id));
create table IMS_ORDERS (
 id number generated always as identity primary key,
 kind varchar2(8) not null check(kind in ('SALE','PURCHASE')),
 shop_id references IMS_SHOP(id) not null, supplier_id references IMS_SUPPLIER(id),
 customer_id references IMS_ACCOUNT(id), actor_id references IMS_ACCOUNT(id) not null,
 created_at date default sysdate not null, received_at date,
 total number(16,2) default 0 not null, paid number(16,2) default 0 not null,
 discount number(16,2) default 0 not null, due_date date, payment varchar2(10));
create table IMS_ORDER_ITEMS (
 order_id references IMS_ORDERS(id), product_id references IMS_PRODUCT(id),
 quantity number(9) not null check(quantity>0), unit_price number(12,2) not null,
 unit_cost number(12,2) not null, primary key(order_id,product_id));
create table IMS_MOVEMENT (
 id number generated always as identity primary key, kind varchar2(10) not null,
 product_id references IMS_PRODUCT(id) not null, shop_id references IMS_SHOP(id) not null,
 target_shop references IMS_SHOP(id), quantity number(9) not null,
 actor_id references IMS_ACCOUNT(id) not null, reason varchar2(500),
 loss number(16,2) default 0 not null, created_at date default sysdate not null);
create table IMS_PAYMENT (
 id number generated always as identity primary key, order_id references IMS_ORDERS(id) not null,
 amount number(16,2) not null check(amount>0), actor_id references IMS_ACCOUNT(id) not null,
 created_at date default sysdate not null);
create table IMS_LOG (
 id number generated always as identity primary key, actor_id references IMS_ACCOUNT(id) not null,
 action varchar2(100) not null, details varchar2(1000), created_at date default sysdate not null);
